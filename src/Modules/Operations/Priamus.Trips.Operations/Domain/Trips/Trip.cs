using Priamus.Trips.SharedKernel.Domain;
using Priamus.Trips.SharedKernel.Results;
using Priamus.Trips.SharedKernel.Security;
using RegistryContracts = Priamus.Trips.Registry.Contracts;

namespace Priamus.Trips.Operations.Domain.Trips;

/// <summary>
/// One job a driver does for one customer with one vehicle: the driver adds it, starts it and ends it. Its
/// state is read from its times alone (<see cref="State"/>). It is priced once, when it is ended, and keeps
/// for good what it was priced with and the documents its contract required. A trip is never removed: a
/// deleted trip stays, marked with who deleted it and when.
/// </summary>
public sealed class Trip : AggregateRoot
{
    /// <summary>How many days after the day it was added a planned trip is still kept.</summary>
    public const int ExpiryDays = 7;

    /// <summary>The longest a trip lasts, in minutes: a day less one minute.</summary>
    public const int MaximumMinutes = 1439;

    private Trip()
    {
        // EF only. Members are populated by EF Core via property setters/backing fields.
        RequiredDocuments = null!;
    }

    private Trip(
        TripId id,
        Guid driverId,
        Guid customerId,
        Guid leadingVehicleId,
        Guid? trailerId,
        Guid? pickupLocationId,
        Guid? deliveryLocationId,
        DateTime addedAt,
        DateOnly addedOn,
        UserId addedBy)
    {
        Id = id;
        DriverId = driverId;
        CustomerId = customerId;
        LeadingVehicleId = leadingVehicleId;
        TrailerId = trailerId;
        PickupLocationId = pickupLocationId;
        DeliveryLocationId = deliveryLocationId;
        AddedAt = addedAt;
        AddedOn = addedOn;
        AddedBy = addedBy;
        RequiredDocuments = [];
    }

    /// <summary>Strongly-typed identifier, generated by the app.</summary>
    public TripId Id { get; private set; }

    /// <summary>The trip number: given when the trip is ended; <c>null</c> before.</summary>
    public long? Number { get; private set; }

    /// <summary>The driver who does the trip.</summary>
    public Guid DriverId { get; private set; }

    /// <summary>The customer the trip is done for.</summary>
    public Guid CustomerId { get; private set; }

    /// <summary>The contract in force on the trip day that priced the trip; <c>null</c> until it is ended.</summary>
    public Guid? ContractId { get; private set; }

    /// <summary>The tractor or standalone vehicle the trip is done with.</summary>
    public Guid LeadingVehicleId { get; private set; }

    /// <summary>The trailer coupled to the tractor; <c>null</c> when none.</summary>
    public Guid? TrailerId { get; private set; }

    /// <summary>Where the trip starts from; <c>null</c> when not named.</summary>
    public Guid? PickupLocationId { get; private set; }

    /// <summary>Where the trip delivers; <c>null</c> when not named.</summary>
    public Guid? DeliveryLocationId { get; private set; }

    /// <summary>When the trip was added (UTC).</summary>
    public DateTime AddedAt { get; private set; }

    /// <summary>The calendar day, in Italy, on which the trip was added: its expiry counts from it.</summary>
    public DateOnly AddedOn { get; private set; }

    /// <summary>The user who added the trip.</summary>
    public UserId AddedBy { get; private set; }

    /// <summary>The calendar day, in Italy, on which the trip started; <c>null</c> until it is started.</summary>
    public DateOnly? Day { get; private set; }

    /// <summary>The start time; <c>null</c> until the trip is started.</summary>
    public TimeOnly? Start { get; private set; }

    /// <summary>The end time; <c>null</c> until the trip is ended.</summary>
    public TimeOnly? End { get; private set; }

    /// <summary>When the trip was ended (UTC); <c>null</c> until it is ended.</summary>
    public DateTime? EndedAt { get; private set; }

    /// <summary>The kilograms carried; <c>null</c> unless the trip is measured by weight.</summary>
    public int? Kilograms { get; private set; }

    /// <summary>The kilometres driven; <c>null</c> unless the trip is measured by distance.</summary>
    public int? Kilometres { get; private set; }

    /// <summary>What the trip records about its size; <c>null</c> until it is ended.</summary>
    public TripMeasureKind? MeasureKind { get; private set; }

    /// <summary>What the trip was priced with and every step of the calculation; <c>null</c> until it is ended.</summary>
    public TripPricing? Pricing { get; private set; }

    /// <summary>The names of the documents the contract required when the trip was ended; empty until then.</summary>
    public IReadOnlyList<string> RequiredDocuments { get; private set; }

    /// <summary>When the trip was deleted (UTC); <c>null</c> when it was not.</summary>
    public DateTime? DeletedAt { get; private set; }

    /// <summary>The user who deleted the trip; <c>null</c> when it was not deleted.</summary>
    public UserId? DeletedBy { get; private set; }

    /// <summary>
    /// The state of the trip, read from its times alone: without a start it is planned, with a start and no
    /// end it is in progress, with both it is ended.
    /// </summary>
    public TripState State => Start is null
        ? TripState.Planned
        : End is null ? TripState.InProgress : TripState.Ended;

    /// <summary>
    /// Tells whether a planned trip added on <paramref name="addedOn"/> is expired on <paramref name="today"/>:
    /// from the eighth day after the day it was added.
    /// </summary>
    /// <param name="addedOn">The day, in Italy, the trip was added.</param>
    /// <param name="today">Today in Italy.</param>
    public static bool IsExpired(DateOnly addedOn, DateOnly today) => addedOn < OldestAddedOnNotExpired(today);

    /// <summary>
    /// The earliest day a planned trip can have been added on and not be expired on <paramref name="today"/>:
    /// the bound that <see cref="IsExpired"/> tests against, for a query that filters by day.
    /// </summary>
    /// <param name="today">Today in Italy.</param>
    public static DateOnly OldestAddedOnNotExpired(DateOnly today) => today.AddDays(-ExpiryDays);

    /// <summary>
    /// The first day of the last seven days ending on <paramref name="today"/>: today and the 6 days before,
    /// the window of the driver's recent ended trips.
    /// </summary>
    /// <param name="today">Today in Italy.</param>
    public static DateOnly FirstDayOfLastSevenDays(DateOnly today) => today.AddDays(-6);

    /// <summary>Tells whether this trip is planned and expired on <paramref name="today"/>.</summary>
    /// <param name="today">Today in Italy.</param>
    public bool IsExpiredOn(DateOnly today) => State == TripState.Planned && IsExpired(AddedOn, today);

    /// <summary>
    /// The days left to a planned trip before it expires on <paramref name="today"/>: 7 on the day it was
    /// added, 0 on its last day.
    /// </summary>
    /// <param name="today">Today in Italy.</param>
    public int DaysToExpiry(DateOnly today) => AddedOn.AddDays(ExpiryDays).DayNumber - today.DayNumber;

    /// <summary>
    /// Adds a planned trip: no day, no time, no pricing and no number. The registry facts are checked
    /// before, by the handler.
    /// </summary>
    /// <param name="id">The identifier the app generated.</param>
    /// <param name="driverId">The driver of the session.</param>
    /// <param name="customerId">The customer.</param>
    /// <param name="leadingVehicleId">The tractor or standalone vehicle.</param>
    /// <param name="trailerId">The trailer; <c>null</c> when none.</param>
    /// <param name="pickupLocationId">The pickup location; <c>null</c> when not named.</param>
    /// <param name="deliveryLocationId">The delivery location; <c>null</c> when not named.</param>
    /// <param name="addedAt">When the trip is added (UTC).</param>
    /// <param name="addedOn">Today in Italy.</param>
    /// <param name="addedBy">The user who adds the trip.</param>
    public static Trip Add(
        TripId id,
        Guid driverId,
        Guid customerId,
        Guid leadingVehicleId,
        Guid? trailerId,
        Guid? pickupLocationId,
        Guid? deliveryLocationId,
        DateTime addedAt,
        DateOnly addedOn,
        UserId addedBy) =>
        new(
            id,
            driverId,
            customerId,
            leadingVehicleId,
            trailerId,
            pickupLocationId,
            deliveryLocationId,
            addedAt,
            addedOn,
            addedBy);

    /// <summary>Starts a planned trip: sets its day and start time together.</summary>
    /// <param name="day">The trip day.</param>
    /// <param name="time">The start time.</param>
    /// <returns>A failure when the trip is not planned.</returns>
    public Result StartAt(DateOnly day, TimeOnly time)
    {
        if (State != TripState.Planned)
        {
            return TripErrors.NotPlanned;
        }

        Day = day;
        Start = time;
        IncrementVersion();
        return Result.Success();
    }

    /// <summary>
    /// Ends a trip in progress: sets its end time and the measure values, and keeps what the registry priced
    /// it with. The measure values must match the measure kind of <paramref name="priced"/>, and the trip
    /// must last 1 to 1439 minutes (an end time not after the start is the day after).
    /// </summary>
    /// <param name="time">The end time.</param>
    /// <param name="kilograms">The kilograms; given only with <see cref="TripMeasureKind.Weight"/>.</param>
    /// <param name="kilometres">The kilometres; given only with <see cref="TripMeasureKind.Distance"/>.</param>
    /// <param name="priced">What the registry priced the trip with.</param>
    /// <param name="number">The trip number the handler took.</param>
    /// <param name="endedAt">When the trip is ended (UTC).</param>
    /// <returns>A failure when the trip is not in progress, its duration is out of range or the measure values do not match.</returns>
    public Result EndAt(
        TimeOnly time,
        int? kilograms,
        int? kilometres,
        RegistryContracts.PricedTrip priced,
        long number,
        DateTime endedAt)
    {
        ArgumentNullException.ThrowIfNull(priced);

        if (State != TripState.InProgress)
        {
            return TripErrors.NotInProgress;
        }

        var kind = MeasureKindOf(priced.Measure);

        // PRD §5.5: each measure is asked for by one pricing mode only. A guard: the registry
        // answers a conflict before a trip is ended with the wrong fields, so no endpoint reaches it.
        if ((kilograms is not null) != (kind == TripMeasureKind.Weight))
        {
            return TripErrors.KilogramsMismatch;
        }

        if ((kilometres is not null) != (kind == TripMeasureKind.Distance))
        {
            return TripErrors.KilometresMismatch;
        }

        var schedule = TripSchedule.Of(Day!.Value, Start!.Value, time);
        var minutes = (schedule.EndsAt!.Value - schedule.StartsAt).TotalMinutes;
        if (minutes is < 1 or > MaximumMinutes)
        {
            return TripErrors.DurationOutOfRange;
        }

        End = time;
        EndedAt = endedAt;
        Kilograms = kilograms;
        Kilometres = kilometres;
        ContractId = priced.ContractId;
        MeasureKind = kind;
        Pricing = PricingOf(priced.Pricing);
        RequiredDocuments = [.. priced.RequiredDocuments];
        Number = number;
        IncrementVersion();
        return Result.Success();
    }

    /// <summary>
    /// Marks a planned trip or a trip in progress as deleted, with who and when. The trip stays in the table.
    /// </summary>
    /// <param name="at">When the trip is deleted (UTC).</param>
    /// <param name="by">The user who deletes the trip.</param>
    /// <returns>A failure when the trip is ended.</returns>
    public Result Delete(DateTime at, UserId by)
    {
        if (State == TripState.Ended)
        {
            return TripErrors.EndedTripCannotBeDeleted;
        }

        DeletedAt = at;
        DeletedBy = by;
        IncrementVersion();
        return Result.Success();
    }

    private static TripMeasureKind MeasureKindOf(RegistryContracts.TripMeasureKind kind) => kind switch
    {
        RegistryContracts.TripMeasureKind.StartAndEnd => TripMeasureKind.StartAndEnd,
        RegistryContracts.TripMeasureKind.Weight => TripMeasureKind.Weight,
        RegistryContracts.TripMeasureKind.Distance => TripMeasureKind.Distance,
        RegistryContracts.TripMeasureKind.StartOnly => TripMeasureKind.StartOnly,
        _ => throw new ArgumentOutOfRangeException(nameof(kind), kind, "Unknown trip measure kind."),
    };

    private static TripRateSource RateSourceOf(RegistryContracts.TripRateSource source) => source switch
    {
        RegistryContracts.TripRateSource.Contract => TripRateSource.Contract,
        RegistryContracts.TripRateSource.Vehicle => TripRateSource.Vehicle,
        RegistryContracts.TripRateSource.Location => TripRateSource.Location,
        RegistryContracts.TripRateSource.LocationPair => TripRateSource.LocationPair,
        _ => throw new ArgumentOutOfRangeException(nameof(source), source, "Unknown trip rate source."),
    };

    private static TripMinimumKind MinimumKindOf(RegistryContracts.TripMinimumKind kind) => kind switch
    {
        RegistryContracts.TripMinimumKind.None => TripMinimumKind.None,
        RegistryContracts.TripMinimumKind.FixedMinimum => TripMinimumKind.FixedMinimum,
        RegistryContracts.TripMinimumKind.TieredOverage => TripMinimumKind.TieredOverage,
        _ => throw new ArgumentOutOfRangeException(nameof(kind), kind, "Unknown trip minimum kind."),
    };

    private static TripPricing PricingOf(RegistryContracts.TripPricing p) => new(
        RateSourceOf(p.RateSource),
        p.RateVehicleId,
        p.RatePickupLocationId,
        p.RateDeliveryLocationId,
        p.DayPrice,
        p.NightPrice,
        p.NightCallFee,
        MinimumKindOf(p.MinimumKind),
        p.MinimumAmount,
        p.MinimumThreshold,
        p.MinimumOveragePrice,
        p.NightBandStart,
        p.NightBandEnd,
        p.NightSurcharge,
        p.IsNight,
        p.Quantity,
        p.UnitPrice,
        p.BaseAmount,
        p.AmountAfterMinimum,
        p.MinimumApplied,
        p.AppliedNightCallFee,
        p.Total);
}
